/**
 * 2026-11-18（会话#14）：**"文件不在了"的标记**。
 *
 * 背景：用户在资源管理器里移动/改名照片时，旧记录会变成"孤儿"。
 * 以前 orphan 对账直接 `db.delete(photos)` —— 标签/相册/收藏跟着级联丢失，
 * 移动过去的文件还会被当成新图重新导入（新 id，标签照样没有）。
 *
 * 现在对账**不删**，只把记录标成"缺失"（`deletedAt` 有值 + 这个批次标记）：
 *   · 图库里看不见（正常查询都带 `deleted_at IS NULL`）；
 *   · 回收站也看不见（`listDeletedPhotos` 会排掉这个批次）；
 *   · 但记录和标签都还在 —— 下次扫描到"同一个文件"（文件名 + 大小 + 修改时间，
 *     且旧路径确实不存在）时，由认亲逻辑把路径改过去并恢复，**标签不丢**；
 *   · 30 天后仍没被认领的，会被回收站的"过期清理"顺手清掉（不额外占空间）。
 */
export const ORPHAN_MISSING_BATCH_ID = "__orphan_missing__";
